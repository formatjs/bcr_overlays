"""Import complete Linux crypto and CBOR source configurations."""
import argparse
import gzip
import json
from pathlib import Path

from import_base import replace_block, sort_archive_files
from import_mojo_runtime import compiler_configuration

ROOT = Path(__file__).resolve().parents[1]
TARGETS = {'crypto': '//crypto:crypto', 'cbor': '//components/cbor:cbor'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('graph', type=Path)
    parser.add_argument('--source-root', type=Path, required=True)
    args = parser.parse_args()
    graph = json.loads(gzip.decompress(args.graph.read_bytes()))
    sources, headers, options, defines = {}, {}, {}, {}
    for name, label in TARGETS.items():
        target = graph['targets'][label]
        sources[name] = [path.removeprefix('//') for path in target['sources']
                         if path.endswith('.cc')]
        directory = label.split(':')[0].removeprefix('//')
        headers[name] = sorted(str(path.relative_to(args.source_root))
                               for path in (args.source_root / directory).rglob('*.h'))
        options[name], defines[name] = compiler_configuration(graph, target)
    inputs = {path for values in [*sources.values(), *headers.values()] for path in values}
    if any(not (args.source_root / path).is_file() for path in inputs):
        raise ValueError('missing crypto input')
    overlay = ROOT / 'bcr/overlay'
    replace_block(overlay / 'BUILD.bazel', '# BEGIN GENERATED CRYPTO INPUTS',
                  '# END GENERATED CRYPTO INPUTS', 'exports_files(' + json.dumps(sorted(inputs), indent=4) + ')')
    data = {'SOURCES': sources, 'HEADERS': headers, 'COPTS': options, 'DEFINES': defines}
    (overlay / 'native/crypto_sources.bzl').write_text('"""Generated by tools/import_crypto.py."""\n\n' +
        '\n\n'.join(key + ' = ' + json.dumps(value, indent=4) for key, value in data.items()) + '\n')
    module = ROOT / 'MODULE.bazel'
    text = module.read_text()
    for filename in ['crypto.bzl', 'crypto_sources.bzl']:
        line = f'        "native/{filename}": "//bcr/overlay/native:{filename}",\n'
        if line not in text:
            marker = text.index('        "native/BUILD.bazel":')
            text = text[:marker] + line + text[marker:]
    module.write_text(sort_archive_files(text))
    print({name: len(paths) for name, paths in sources.items()})


if __name__ == '__main__':
    main()
