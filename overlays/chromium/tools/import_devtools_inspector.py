"""Import Chromium's original DevTools inspector-overlay resource closure."""

import argparse
import gzip
import hashlib
import json
from pathlib import Path

from import_base import sort_archive_files

ROOT = Path(__file__).resolve().parents[1]
BUILD = '//out/bazel-import/'
PREFIX = '//third_party/devtools-frontend/src/'
ROOT_TARGET = PREFIX.rstrip('/') + ':generate_devtools_inspector_overlay_resources'
SCRIPTS = {
    PREFIX + 'scripts/build/build_inspector_overlay.py',
    PREFIX + 'scripts/build/typescript/ts_library.py',
}
ESBUILD = PREFIX + 'third_party/esbuild/esbuild'


def target_name(label):
    return 'devtools_inspector_' + hashlib.sha256(label.encode()).hexdigest()[:16]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('graph', type=Path)
    parser.add_argument('--source-root', type=Path, required=True)
    args = parser.parse_args()
    graph = json.loads(gzip.decompress(args.graph.read_bytes()))
    targets = graph['targets']
    selected = {}
    pending = [label for label in targets if label.partition('(')[0] == ROOT_TARGET]
    while pending:
        label = pending.pop()
        if label in selected:
            continue
        target = targets[label]
        if target['type'] not in ('action', 'copy', 'group'):
            raise ValueError('unmapped DevTools target: ' + label)
        if target['type'] == 'action' and target['script'] not in SCRIPTS:
            raise ValueError('unmapped DevTools script: ' + target['script'])
        selected[label] = target
        pending.extend(target.get('deps', []))

    def file_label(path):
        if path.startswith(BUILD):
            return ':' + path.removeprefix(BUILD)
        if not path.startswith('//') or not (args.source_root / path[2:]).is_file():
            raise ValueError('missing DevTools input: ' + path)
        if path.startswith(PREFIX):
            return '@chromium_devtools_frontend//:' + path.removeprefix(PREFIX)
        if path.startswith('//third_party/node/'):
            return '//:' + path[2:]
        raise ValueError('unmapped DevTools input: ' + path)

    actions, copies, groups = [], [], []
    for label, target in sorted(selected.items()):
        deps = [':' + target_name(dep) for dep in target.get('deps', [])]
        paths = set(target.get('inputs', []) + target.get('sources', []))
        if target['type'] == 'action':
            paths.add(target['script'])
            paths.discard(ESBUILD)
            deps += [':devtools_inspector_runtime', ':devtools_inspector_npm', ':webui_node_inputs', ':webui_python_inputs']
            if target['script'].endswith('/ts_library.py'):
                deps.append(':devtools_inspector_esbuild_inputs')
        files = {file_label(path): path[2:] for path in sorted(paths)}
        if target['type'] == 'action':
            actions.append(dict(
                name=target_name(label), srcs=files,
                outs={path.removeprefix(BUILD): path.removeprefix(BUILD) for path in target['outputs']},
                script=target['script'][2:], args=target['args'], deps=deps,
            ))
        elif target['type'] == 'copy':
            sources, destinations = target.get('sources', []), target['outputs']
            if len(sources) != len(destinations):
                raise ValueError('DevTools copy source/output mismatch: ' + label)
            outputs = {destination.removeprefix(BUILD): path[2:]
                       for path, destination in zip(sources, destinations)}
            if set(outputs) != {path.removeprefix(BUILD) for path in target['outputs']}:
                raise ValueError('DevTools copy output mismatch: ' + label)
            copies.append(dict(name=target_name(label), srcs=files, outputs=outputs, deps=deps))
        else:
            groups.append(dict(name=target_name(label), srcs=files, deps=deps))

    support = [PREFIX + 'scripts/devtools_paths.py']
    data = dict(ACTIONS=actions, COPIES=copies, GROUPS=groups,
                SUPPORT={file_label(path): path[2:] for path in support})
    overlay = ROOT / 'bcr/overlay/native'
    (overlay / 'devtools_inspector_sources.bzl').write_text(
        '"""Generated by tools/import_devtools_inspector.py."""\n\n' +
        '\n\n'.join(key + ' = ' + json.dumps(value, indent=4) for key, value in data.items()) + '\n')
    (overlay / 'devtools_inspector_targets.json').write_text(
        json.dumps({label: target_name(label) for label in sorted(selected)}, indent=2) + '\n')
    module = ROOT / 'MODULE.bazel'
    text = module.read_text()
    for filename in ['devtools_inspector.bzl', 'devtools_inspector_sources.bzl', 'devtools_inspector_targets.json']:
        line = f'        "native/{filename}": "//bcr/overlay/native:{filename}",\n'
        if line not in text:
            marker = text.index('        "native/BUILD.bazel":')
            text = text[:marker] + line + text[marker:]
    module.write_text(sort_archive_files(text))
    print(len(actions), 'original DevTools actions;', len(copies), 'copies;',
          sum(len(target.get('outputs', [])) for target in selected.values()), 'outputs')


if __name__ == '__main__':
    main()
