"""Import every Perfetto schema generator from Chromium's captured browser graph."""
import gzip
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
BUILD_DIR = '//out/bazel-import/'
TOOLS = ['protozero_plugin', 'cppgen_plugin', 'ipc_plugin']


def main():
    graph = json.loads(gzip.decompress(Path(sys.argv[1]).read_bytes()))
    targets = {label: target for label, target in graph['targets'].items()
               if label.startswith(('//third_party/perfetto/', '//base/tracing/protos:'))
               and target.get('script') == '//tools/protoc_wrapper/protoc_wrapper.py'}
    lines = ['"""Generated by tools/import_perfetto_proto.py; native Perfetto schema actions."""', '',
             'load(":python_action.bzl", "chromium_python_action", "chromium_filegroup")',
             'load(":tool_inputs.bzl", "chromium_tool_inputs")',
             'load("@rules_cc//cc:cc_library.bzl", "cc_library")', '',
             'def native_perfetto_proto(name):',
             '    """Generate original browser tracing protocols with native host tools.', '',
             '    Args:', '        name: Generated protocol output group.', '    """']
    tool_paths = {tool: {path for target in targets.values() for path in target['inputs']
                         if path.startswith(BUILD_DIR) and Path(path).name == tool}
                  for tool in TOOLS}
    if any(len(paths) > 1 or (tool != 'ipc_plugin' and not paths)
           for tool, paths in tool_paths.items()):
        raise ValueError('expected one execution-platform path per Perfetto plugin')
    tool_paths = {tool: paths.pop() for tool, paths in tool_paths.items() if paths}
    for tool in tool_paths:
        lines += ['    chromium_tool_inputs(', f'        name = "perfetto_{tool}_tool",',
                  f'        tool = "@perfetto//:{tool}",',
                  '        logical_path = ' + json.dumps(tool_paths[tool][2:]) + ',', '    )']
    names = {}
    generated = set()
    for label, target in sorted(targets.items()):
        name = 'perfetto_proto_' + hashlib.sha256(label.encode()).hexdigest()[:16]
        names[label] = name
        files = {}
        deps = [':protoc_tool']
        for path in sorted(set(target['inputs'] + [target['script']])):
            logical = path[2:]
            if path.startswith(BUILD_DIR) and Path(path).name == 'protoc':
                continue
            if path in tool_paths.values():
                deps.append(':perfetto_' + Path(path).name + '_tool')
                continue
            if path == '//third_party/protobuf/src/google/protobuf/descriptor.proto':
                file_label = '@protobuf//:descriptor_proto_srcs'
            elif path.startswith('//third_party/perfetto/protos/'):
                file_label = '@perfetto//:' + path.removeprefix('//third_party/perfetto/')
            elif path == '//tools/protoc_wrapper/protoc_wrapper.py' or path.startswith('//base/tracing/protos/'):
                file_label = '//:' + logical
            else:
                raise ValueError(f'unmapped input: {path}')
            files[file_label] = logical
        if any(not path.startswith(BUILD_DIR) for path in target['outputs']):
            raise ValueError(f'unsupported outputs: {label}')
        outs = {path.removeprefix(BUILD_DIR): path.removeprefix(BUILD_DIR) for path in target['outputs']}
        generated.update(outs)
        lines += ['    chromium_python_action(', f'        name = "{name}",',
                  '        srcs = ' + json.dumps(files) + ',',
                  '        outs = ' + json.dumps(outs) + ',',
                  '        script = "tools/protoc_wrapper/protoc_wrapper.py",',
                  '        args = ' + json.dumps(target['args']) + ',',
                  '        deps = ' + json.dumps(sorted(set(deps))) + ',', '    )']
    lines += ['    chromium_filegroup(', '        name = name,',
              '        deps = ' + json.dumps([':' + name for name in names.values()]) + ',', '    )', '']
    lines += ['    cc_library(', '        name = name + "_cpp",',
              '        srcs = ' + json.dumps([':' + path for path in sorted(generated) if path.startswith('gen/') and path.endswith('.cc') and not path.endswith('.ipc.cc')]) + ',',
              '        hdrs = ' + json.dumps([':' + path for path in sorted(generated) if path.startswith('gen/') and path.endswith('.h') and not path.endswith('.ipc.h')]) + ',',
              '        includes = ["gen/third_party/perfetto", "gen"],',
              '        copts = select({"@platforms//os:windows": ["/std:c++20", "/GR-", "/EHs-c-"], "//conditions:default": ["-std=c++20", "-fno-rtti", "-fno-exceptions"]}),',
              '        deps = ["@perfetto//:chromium_protozero", ":protobuf_lite_runtime"],',
              '    )', '']
    (ROOT / 'bcr/overlay/native/perfetto_proto.bzl').write_text('\n'.join(lines))
    (ROOT / 'bcr/overlay/native/perfetto_proto_targets.json').write_text(json.dumps(names, indent=2) + '\n')
    print(f'Imported {len(names)} Perfetto protocol generators')


if __name__ == '__main__':
    main()
