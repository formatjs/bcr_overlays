"""Import complete Chromium QUICHE configuration; dependencies stay bundled."""
import argparse
import gzip
import json
from pathlib import Path

from import_base import replace_block, sort_archive_files
from import_mojo_runtime import compiler_configuration

ROOT = Path(__file__).resolve().parents[1]
PREFIX = 'net/third_party/quiche/src/'
TARGETS = {
    'quiche': '//net/third_party/quiche:quiche',
    'uri_template': '//net/third_party/uri_template:uri_template',
    'quic_proto': '//net/third_party/quiche:net_quic_proto',
}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('graph', type=Path)
    parser.add_argument('--source-root', type=Path, required=True)
    args = parser.parse_args()
    graph = json.loads(gzip.decompress(args.graph.read_bytes()))
    sources, headers, options, defines = {}, {}, {}, {}
    archive_inputs = set()
    for name, label in TARGETS.items():
        target = graph['targets'][label]
        paths = [p.removeprefix('//out/bazel-import/').removeprefix('//')
                 for p in target['sources']]
        def source_label(path):
            if path.startswith('gen/'):
                return ':' + path
            if path.startswith(PREFIX):
                return '@chromium_quiche//:' + path
            archive_inputs.add(path)
            if not (args.source_root / path).is_file():
                raise ValueError('missing source: ' + path)
            return '//:' + path
        sources[name] = [source_label(p) for p in paths if p.endswith('.cc')]
        headers[name] = [source_label(p) for p in paths if p.endswith(('.h', '.inc'))
                         and not p.startswith(PREFIX)]
        options[name], defines[name] = compiler_configuration(graph, target)
        # Protobuf 33 forward-declares a member-pointer base in constexpr metadata.
        # LLVM's completeness diagnostic rejects that valid declaration.
        if name in ('quiche', 'quic_proto'):
            options[name] = [flag for flag in options[name]
                             if flag != '-fcomplete-member-pointers']
    overlay = ROOT / 'bcr/overlay'
    replace_block(overlay / 'BUILD.bazel', '# BEGIN GENERATED QUICHE INPUTS',
                  '# END GENERATED QUICHE INPUTS',
                  'exports_files(' + json.dumps(sorted(archive_inputs), indent=4) + ')')
    data = {'SOURCES': sources, 'HEADERS': headers, 'COPTS': options, 'DEFINES': defines}
    (overlay / 'native/quiche_sources.bzl').write_text(
        '\"\"\"Generated by tools/import_quiche.py.\"\"\"\n\n' +
        '\n\n'.join(k + ' = ' + json.dumps(v, indent=4) for k, v in data.items()) + '\n')
    module = ROOT / 'MODULE.bazel'
    text = module.read_text()
    for filename in ['quiche.bzl', 'quiche_sources.bzl', 'dependencies.bzl', 'quiche_repository.BUILD.bazel']:
        line = f'        "native/{filename}": "//bcr/overlay/native:{filename}",\n'
        if line not in text:
            marker = text.index('        "native/BUILD.bazel":')
            text = text[:marker] + line + text[marker:]
    module.write_text(sort_archive_files(text))
    print({k: len(v) for k, v in sources.items()})

if __name__ == '__main__':
    main()
