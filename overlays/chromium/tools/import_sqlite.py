"""Import original Chromium SQLite C compiler and public header configuration."""
import argparse
import gzip
import json
from pathlib import Path

from import_base import replace_block, sort_archive_files
from import_mojo_runtime import compiler_configuration

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('graph', type=Path)
    args = parser.parse_args()
    graph = json.loads(gzip.decompress(args.graph.read_bytes()))
    target = graph['targets']['//third_party/sqlite:chromium_sqlite3']
    copts, defines = compiler_configuration(graph, dict(target, cflags_cc=target['cflags_c']))
    overlay = ROOT / 'bcr/overlay'
    files = ['third_party/sqlite/sqlite3_shim.c', 'third_party/sqlite/sqlite3_shim_fixups.h',
             'third_party/sqlite/sqlite3.h']
    replace_block(overlay / 'BUILD.bazel', '# BEGIN BUNDLED SQLITE INPUTS',
                  '# END BUNDLED SQLITE INPUTS', 'exports_files(' + json.dumps(files, indent=4) + ')')
    output = '"""Generated by tools/import_sqlite.py from original GN configuration."""\n\n'
    output += 'COPTS = ' + json.dumps(copts, indent=4) + '\n\n'
    output += 'DEFINES = ' + json.dumps(defines, indent=4) + '\n'
    (overlay / 'native/sqlite_sources.bzl').write_text(output)
    module = ROOT / 'MODULE.bazel'
    text = module.read_text()
    for filename in ['sqlite.bzl', 'sqlite_sources.bzl']:
        line = f'        "native/{filename}": "//bcr/overlay/native:{filename}",\n'
        if line not in text:
            marker = text.index('        "native/BUILD.bazel":')
            text = text[:marker] + line + text[marker:]
    module.write_text(sort_archive_files(text))


if __name__ == '__main__':
    main()
