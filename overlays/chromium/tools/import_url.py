"""Import complete URL library and original Mojo URL/origin traits."""
import argparse
import gzip
import json
from pathlib import Path

from import_base import replace_block, sort_archive_files
from import_mojo_runtime import compiler_configuration

ROOT = Path(__file__).resolve().parents[1]
TARGETS = {
    'url': '//url:url',
    'traits': '//url/mojom:mojom_traits',
    'gurl': '//url/mojom:url_mojom_gurl',
    'origin': '//url/mojom:url_mojom_origin',
    'scheme_host_port': '//url/mojom:url_mojom_scheme_host_port',
    'gurl_shared': '//url/mojom:url_mojom_gurl_shared_cpp_sources',
    'origin_shared': '//url/mojom:url_mojom_origin_shared_cpp_sources',
    'scheme_host_port_shared': '//url/mojom:url_mojom_scheme_host_port_shared_cpp_sources',
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('graph', type=Path)
    parser.add_argument('--source-root', type=Path, required=True)
    args = parser.parse_args()
    graph = json.loads(gzip.decompress(args.graph.read_bytes()))
    sources, options, defines = {}, {}, {}
    for name, label in TARGETS.items():
        target = graph['targets'][label]
        sources[name] = [path.removeprefix('//out/bazel-import/').removeprefix('//')
                         for path in target.get('sources', []) if path.endswith('.cc')]
        options[name], defines[name] = compiler_configuration(graph, target)
    headers = sorted(str(path.relative_to(args.source_root))
                     for path in (args.source_root / 'url').rglob('*.h'))
    generated = sorted({path.removeprefix('//out/bazel-import/')
                        for target in graph['targets'].values() for path in target.get('outputs', [])
                        if path.startswith('//out/bazel-import/gen/url/mojom/') and path.endswith('.h')})
    inputs = set(headers) | {path for values in sources.values() for path in values if not path.startswith('gen/')}
    if any(not (args.source_root / path).is_file() for path in inputs):
        raise ValueError('missing URL source input')
    overlay = ROOT / 'bcr/overlay'
    replace_block(overlay / 'BUILD.bazel', '# BEGIN GENERATED URL INPUTS',
                  '# END GENERATED URL INPUTS', 'exports_files(' + json.dumps(sorted(inputs), indent=4) + ')')
    data = {'SOURCES': sources, 'HEADERS': headers, 'GENERATED_HEADERS': generated,
            'COPTS': options, 'DEFINES': defines}
    (overlay / 'native/url_sources.bzl').write_text('"""Generated by tools/import_url.py."""\n\n' +
        '\n\n'.join(key + ' = ' + json.dumps(value, indent=4) for key, value in data.items()) + '\n')
    module = ROOT / 'MODULE.bazel'
    text = module.read_text()
    for filename in ['url.bzl', 'url_sources.bzl']:
        line = f'        "native/{filename}": "//bcr/overlay/native:{filename}",\n'
        if line not in text:
            marker = text.index('        "native/BUILD.bazel":')
            text = text[:marker] + line + text[marker:]
    module.write_text(sort_archive_files(text))
    print(f'Imported {sum(map(len, sources.values()))} URL/Mojo C++ sources and {len(headers)} headers')


if __name__ == '__main__':
    main()
