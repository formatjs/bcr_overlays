"""Import Chromium's vendored libxslt with its captured C configuration."""

import argparse
import gzip
import json
from pathlib import Path

from import_base import replace_block, sort_archive_files
from import_mojo_runtime import compiler_configuration

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('graph', type=Path)
    parser.add_argument('--source-root', type=Path, required=True)
    args = parser.parse_args()
    graph = json.loads(gzip.decompress(args.graph.read_bytes()))
    target = graph['targets']['//third_party/libxslt:libxslt']
    files = sorted({path.removeprefix('//') for path in target['sources']})
    for path in files:
        if not path.startswith('third_party/libxslt/'):
            raise ValueError(f'unmapped libxslt input: {path}')
        if not (args.source_root / path).is_file():
            raise FileNotFoundError(path)
    copts, defines = compiler_configuration(
        graph, dict(target, cflags_cc=target['cflags_c']))
    sources = [path for path in files if path.endswith('.c')]
    headers = [path for path in files if path.endswith('.h')]
    if len(sources) + len(headers) != len(files):
        raise ValueError('unmapped libxslt source type')
    overlay = ROOT / 'bcr/overlay'
    replace_block(
        overlay / 'BUILD.bazel', '# BEGIN NATIVE XSLT INPUTS',
        '# END NATIVE XSLT INPUTS',
        'exports_files(' + json.dumps(files, indent=4) + ')')
    output = '\n'.join([
        '"""Generated by tools/import_xslt.py from the captured GN target."""',
        '',
        'load("@rules_cc//cc:cc_library.bzl", "cc_library")',
        '',
        'def native_xslt():',
        '    cc_library(',
        '        name = "libxslt",',
        '        srcs = ' + json.dumps(['//:' + path for path in sources]) + ',',
        '        hdrs = ' + json.dumps(['//:' + path for path in headers]) + ',',
        '        includes = ["..", "../third_party/libxslt/linux",',
        '                    "../third_party/libxslt/src",',
        '                    "../third_party/libxslt/src/libxslt"],',
        '        copts = ' + json.dumps(copts) + ',',
        '        local_defines = ' + json.dumps(defines) + ',',
        '        linkstatic = True,',
        '        deps = [":libxml"],',
        '    )',
        '',
    ])
    (overlay / 'native/xslt.bzl').write_text(output)
    build = overlay / 'native/BUILD.bazel'
    text = build.read_text()
    if 'load(":xslt.bzl", "native_xslt")' not in text:
        text = text.replace('load(":sqlite.bzl", "native_sqlite")',
                            'load(":sqlite.bzl", "native_sqlite")\n'
                            'load(":xslt.bzl", "native_xslt")')
        text = text.replace('    "sqlite.bzl",', '    "sqlite.bzl",\n    "xslt.bzl",')
        text += '\nnative_xslt()\n'
    build.write_text(text)
    for path in (overlay / 'native').glob('*.bzl'):
        original = path.read_text()
        rewritten = original.replace('@libxslt//libxslt', ':libxslt').replace(
            '@libxslt//:libxslt', ':libxslt')
        if rewritten != original:
            path.write_text(rewritten)
    module = ROOT / 'MODULE.bazel'
    text = module.read_text()
    mapping = '        "native/xslt.bzl": "//bcr/overlay/native:xslt.bzl",\n'
    if mapping not in text:
        index = text.index('        "native/BUILD.bazel":')
        text = text[:index] + mapping + text[index:]
    module.write_text(sort_archive_files(text))
    print(f'Imported native libxslt: {len(sources)} C sources, {len(headers)} headers')


if __name__ == '__main__':
    main()
