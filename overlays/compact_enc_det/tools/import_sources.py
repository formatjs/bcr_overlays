"""Import Compact Encoding Detection's exact Chromium source configuration."""
import gzip
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def main():
    graph = json.loads(gzip.decompress(Path(sys.argv[1]).read_bytes()))
    source = Path(sys.argv[2])
    target = graph['targets']['//third_party/ced:ced']
    prefix = '//third_party/ced/src/'
    if any(not path.startswith(prefix) for path in target['sources']):
        raise ValueError('source outside CED')
    sources = [path.removeprefix(prefix) for path in target['sources'] if path.endswith('.cc')]
    headers = sorted(str(path.relative_to(source)) for path in source.rglob('*.h'))
    if any(not (source / path).is_file() for path in sources):
        raise ValueError('missing CED source')
    unpack = lambda key: graph['pool'][target[key]['pool']]
    flags = []
    iterator = iter(unpack('cflags') + unpack('cflags_cc'))
    for flag in iterator:
        if flag == '-Xclang':
            argument = next(iterator)
            if argument not in ('-fmodule-file-home-is-cwd', '-fmodules-local-submodule-visibility'):
                raise ValueError(f'unmapped frontend flag: {argument}')
            continue
        if flag in ('-Werror', '-nostdinc++') or flag.startswith((
                '-fcrash-diagnostics-dir=', '--warning-suppression-mappings=', '--target=',
                '--sysroot=', '-isystem', '-fmodules', '-fno-implicit-module',
                '-fbuiltin-module-map', '-fmodule-map-file=')):
            continue
        flags.append(flag)
    defines = [value for value in unpack('defines') if not value.startswith((
        'CR_LIBCXX_REVISION=', 'CR_SYSROOT_KEY=', 'USE_LIBCXX_MODULES'))]
    data = {'SOURCES': sources, 'HEADERS': headers, 'COPTS': flags, 'DEFINES': defines}
    (ROOT / 'bcr/overlay/chromium_sources.bzl').write_text(
        '"""Generated by tools/import_sources.py from Chromium Linux graph."""\n\n' +
        '\n\n'.join(key + ' = ' + json.dumps(value, indent=4) for key, value in data.items()) + '\n')
    print(f'Imported {len(sources)} C++ sources, {len(headers)} headers')


if __name__ == '__main__':
    main()
