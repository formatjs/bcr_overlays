"""Import Compact Encoding Detection's exact Chromium source configuration."""
import argparse
import gzip
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT.parent / 'chromium/tools'))
from import_mojo_runtime import compiler_configuration
sys.path.pop(0)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('graph', type=Path)
    parser.add_argument('source', type=Path)
    parser.add_argument('--arm64-graph', type=Path)
    parser.add_argument('--darwin-arm64-graph', type=Path)
    parser.add_argument('--windows-amd64-graph', type=Path)
    parser.add_argument('--windows-arm64-graph', type=Path)
    args = parser.parse_args()
    graph = json.loads(gzip.decompress(args.graph.read_bytes()))
    source = args.source
    target = graph['targets']['//third_party/ced:ced']
    prefix = '//third_party/ced/src/'
    if any(not path.startswith(prefix) for path in target['sources']):
        raise ValueError('source outside CED')
    sources = [path.removeprefix(prefix) for path in target['sources'] if path.endswith('.cc')]
    headers = sorted(str(path.relative_to(source)) for path in source.rglob('*.h'))
    if any(not (source / path).is_file() for path in sources):
        raise ValueError('missing CED source')
    flags, defines = compiler_configuration(graph, target)
    data = {'SOURCES': sources, 'HEADERS': headers, 'COPTS': flags, 'DEFINES': defines}
    selected = {}
    profiles = {'COPTS': {}, 'DEFINES': {}}
    for platform, path in [
        ('linux_arm64', args.arm64_graph),
        ('darwin_arm64', args.darwin_arm64_graph),
        ('windows_amd64', args.windows_amd64_graph),
        ('windows_arm64', args.windows_arm64_graph),
    ]:
        if not path:
            continue
        capture = json.loads(gzip.decompress(path.read_bytes()))
        platform_target = capture['targets']['//third_party/ced:ced']
        platform_sources = [path.removeprefix(prefix) for path in platform_target['sources'] if path.endswith('.cc')]
        if set(platform_sources) != set(data['SOURCES']):
            raise ValueError(platform + ' source list differs; add per-target source selection')
        platform_flags, platform_defines = compiler_configuration(capture, platform_target)
        for key, value in [('COPTS', platform_flags), ('DEFINES', platform_defines)]:
            profiles[key]['//:' + platform] = value
    for key, values in profiles.items():
        if values:
            values['//conditions:default'] = data[key]
            text = re.sub(r'"(//:[^"]+)"', r'Label("\1")', json.dumps(values, indent=4))
            selected[key] = 'select(' + text + ')'
    (ROOT / 'bcr/overlay/chromium_sources.bzl').write_text(
        '"""Generated by tools/import_sources.py from Chromium graphs."""\n\n' +
        '\n\n'.join(key + ' = ' + (selected[key] if key in selected else json.dumps(value, indent=4)) for key, value in data.items()) + '\n')
    print(f'Imported {len(sources)} C++ sources, {len(headers)} headers')


if __name__ == '__main__':
    main()
