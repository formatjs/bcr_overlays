"""Import pinned ipcz sources and Chromium configuration without running GN."""
import argparse
import gzip
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT.parent / 'chromium/tools'))
from import_mojo_runtime import compiler_configuration
sys.path.pop(0)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('graph', type=Path)
    parser.add_argument('source', type=Path)
    parser.add_argument('--arm64-graph', type=Path)
    args = parser.parse_args()
    graph = json.loads(gzip.decompress(args.graph.read_bytes()))
    source = args.source
    prefix = '//third_party/ipcz/'
    targets = [graph['targets']['//third_party/ipcz/src:' + name]
               for name in ['ipcz_chromium', 'impl_chromium', 'util_chromium']]
    files = sorted({path for target in targets for path in target.get('sources', [])})
    if any(not path.startswith(prefix) for path in files):
        raise ValueError('ipcz source outside canonical directory')
    sources = [path[2:] for path in files if path.endswith('.cc')]
    headers = sorted(str(path.relative_to(source))
                     for directory in ['include', 'src/ipcz', 'src/util', 'src/standalone/base']
                     for path in (source / 'third_party/ipcz' / directory).rglob('*.h'))
    headers.append('third_party/ipcz/src/api.h')
    flags, defines = compiler_configuration(graph, targets[0])
    data = {'CORE_SOURCES': sources, 'CORE_HEADERS': sorted(headers),
            'CHROMIUM_DEFINES': defines, 'COPTS': flags}
    selected = {}
    if args.arm64_graph:
        arm = json.loads(gzip.decompress(args.arm64_graph.read_bytes()))
        arm_target = arm['targets']['//third_party/ipcz/src:ipcz_chromium']
        arm_sources = [path[2:] for target in [arm['targets']['//third_party/ipcz/src:' + name] for name in ['ipcz_chromium', 'impl_chromium', 'util_chromium']] for path in target.get('sources', []) if path.endswith('.cc')]
        if set(arm_sources) != set(data['CORE_SOURCES']):
            raise ValueError('ARM64 source list differs; add per-target source selection')
        arm_flags, arm_defines = compiler_configuration(arm, arm_target)
        for key, value in [('COPTS', arm_flags), ('CHROMIUM_DEFINES', arm_defines)]:
            selected[key] = 'select(' + json.dumps({
                '@platforms//cpu:aarch64': value,
                '//conditions:default': data[key],
            }, indent=4) + ')'
    overlay = ROOT / 'bcr/overlay'
    (overlay / 'bazel/sources.bzl').write_text('"""Generated by tools/import_sources.py."""\n\n' +
        '\n\n'.join(key + ' = ' + (selected[key] if key in selected else json.dumps(value, indent=4)) for key, value in data.items()) + '\n')
    includes = set()
    for path in (source / 'third_party/ipcz/src').rglob('*'):
        if path.suffix not in ('.h', '.cc') or 'test' in path.parts or '_test' in path.name:
            continue
        includes.update(re.findall(r'#include "third_party/abseil-cpp/(absl/[^\"]+)"', path.read_text()))
    for header in sorted(includes):
        path = overlay / 'absl_forward' / header.removeprefix('absl/')
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text('#include "' + header + '"\n')
    print(f'Imported {len(sources)} core C++ sources, {len(headers)} headers, {len(includes)} Abseil forwarders')


if __name__ == '__main__':
    main()
