"""Import NSPR 4.29's Linux pthread source lists from upstream Makefiles."""
import argparse
import json
from pathlib import Path
import re


def c_sources(root, directory):
    text = (root / directory / 'Makefile.in').read_text()
    block = text.split('CSRCS =', 1)[1].split('$(NULL)', 1)[0]
    return [str(Path(directory) / name) for name in re.findall(r'\b[\w]+\.c\b', block)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source_root', type=Path)
    args = parser.parse_args()
    root = args.source_root
    text = (root / 'pr/src/Makefile.in').read_text()
    block = text.split('OBJS =', 1)[1].split('ifdef USE_PTHREADS', 1)[0]
    core = ['pr/src/' + directory + name + '.c' for directory, name in
            re.findall(r'([\w/]*)\$\(OBJDIR\)/([\w]+)\.\$\(OBJ_SUFFIX\)', block)]
    core += c_sources(root, 'pr/src/pthreads')
    core += c_sources(root, 'pr/src/md/unix')
    core += ['pr/src/md/unix/linux.c', 'pr/src/md/unix/os_Linux_x86_64.s']
    sources = {'NSPR': core, 'PLC': c_sources(root, 'lib/libc/src'),
               'PLDS': c_sources(root, 'lib/ds')}
    for paths in sources.values():
        if any(not (root / path).is_file() for path in paths):
            raise ValueError('missing upstream source')
        if len(paths) != len(set(paths)):
            raise ValueError('duplicate upstream source')
    destination = Path(__file__).resolve().parents[1] / 'bcr/overlay/bazel/sources.bzl'
    destination.write_text('"""Generated by tools/import_sources.py."""\n\n' +
        '\n\n'.join(name + '_SOURCES = ' + json.dumps(paths, indent=4)
                    for name, paths in sources.items()) + '\n')
    print({name: len(paths) for name, paths in sources.items()})


if __name__ == '__main__':
    main()
