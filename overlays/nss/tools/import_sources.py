"""Import resolved NSS Linux Release targets from maintainer-only GYP dumps."""
import argparse
import ast
import json
import posixpath
import re
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source_root', type=Path)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    root = args.source_root
    targets, exports = {}, {}
    for file in sorted(root.rglob('*.gypd')):
        directory = file.parent.relative_to(root).as_posix()
        normalize = lambda path: posixpath.normpath(directory + '/' + path)
        for target in ast.literal_eval(file.read_text()).get('targets', []):
            name = target['target_name']
            if name in targets:
                raise ValueError('duplicate target: ' + name)
            configuration = target['configurations']['Release']
            if name == 'shlibsign':
                manifest = (file.parent / 'manifest.mn').read_text()
                for define, variable in [('SHLIB_VERSION', 'LIBRARY_VERSION'),
                                         ('SOFTOKEN_SHLIB_VERSION', 'SOFTOKEN_LIBRARY_VERSION')]:
                    match = re.search(r'^' + variable + r'\s*=\s*(\d+)\s*$', manifest, re.MULTILINE)
                    if not match:
                        raise ValueError('missing Debian shlibsign version: ' + variable)
                    configuration['defines'].append(f'{define}="{match.group(1)}"')
            sources = []
            for path in target.get('sources', []):
                if path.startswith('<(INTERMEDIATE_DIR)/'):
                    if path.endswith('/certdata.c'):
                        sources.append(':certdata_source')
                    elif not path.endswith('.def'):
                        raise ValueError('unmapped generated source: ' + path)
                else:
                    path = normalize(path)
                    if not (root / path).is_file():
                        raise ValueError('missing source: ' + path)
                    sources.append(path)
            includes = []
            for path in configuration.get('include_dirs', []):
                if path.startswith('/native/nspr/'):
                    continue
                if path.startswith('/native/nss/'):
                    path = path.replace('/native/nss/', 'include/', 1)
                else:
                    path = normalize(path)
                includes.append(path)
            mapfile = target.get('variables', {}).get('mapfile', '')
            entry = {
                'type': target['type'], 'sources': sources,
                'deps': sorted({value.split(':')[1].split('#')[0]
                                for value in target.get('dependencies', [])}),
                'copts': [value for value in configuration.get('cflags', [])
                          if value not in ['-Werror', '-no-integrated-as']],
                'conlyopts': configuration.get('cflags_c', []),
                'cxxopts': configuration.get('cflags_cc', []),
                'defines': [value.replace('"', '\\"') for value in configuration.get('defines', [])],
                'includes': includes,
                'linkopts': [value for value in configuration.get('ldflags', [])
                             if '--version-script' not in value],
                'mapfile': normalize(mapfile) if mapfile else '',
                'libraries': target.get('libraries', []),
            }
            targets[name] = entry
            for copy in target.get('copies', []):
                destination = copy['destination'].removeprefix('/native/nss/')
                for source in copy['files']:
                    output = destination + '/' + Path(source).name
                    source = normalize(source)
                    if output in exports and exports[output] != source:
                        raise ValueError('conflicting export: ' + output)
                    exports[output] = source
    for entry in targets.values():
        missing = set(entry['deps']) - targets.keys()
        if missing:
            raise ValueError('unresolved dependency: ' + ', '.join(sorted(missing)))
    overlay = Path(__file__).resolve().parents[1] / 'bcr/overlay'
    output = args.output or overlay / 'bazel/sources.bzl'
    output.write_text('"""Generated by tools/import_sources.py."""\n\n' +
        'TARGETS = ' + json.dumps(targets, indent=4, sort_keys=True) + '\n\n' +
        'EXPORTS = ' + json.dumps(exports, indent=4, sort_keys=True) + '\n')
    print(f'Imported {len(targets)} NSS targets, {len(exports)} exported files')


if __name__ == '__main__':
    main()
